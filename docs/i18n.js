function trText(s) {
  if (LANG !== 'kk' || !s) return s;
  const raw = s.trim();
  if (!raw || !/[А-Яа-яЁё]/.test(raw)) return s;
  const lead = s.slice(0, s.indexOf(raw)), trail = s.slice(s.indexOf(raw) + raw.length);
  const t = raw.replace(/\s+/g, ' ');
  if (Object.prototype.hasOwnProperty.call(KK, t)) return lead + KK[t] + trail;
  let out = t;
  for (const [re, rep] of KK_PATTERNS) if (re.test(out)) { out = out.replace(re, rep); break; }
  for (const [a, b] of KK_PARTS) if (out.includes(a)) out = out.split(a).join(b);
  return lead + out + trail;
}

const SKIP = new Set(['SCRIPT', 'STYLE', 'TEXTAREA', 'svg', 'SVG']);
function trNode(root) {
  if (LANG !== 'kk' || !root) return;
  if (root.nodeType === Node.TEXT_NODE) {
    if (root.parentNode && !SKIP.has(root.parentNode.nodeName) && !root.parentNode.closest?.('[translate="no"]')) {
      const v = trText(root.nodeValue);
      if (v !== root.nodeValue) root.nodeValue = v;
    }
    return;
  }
  if (root.nodeType !== Node.ELEMENT_NODE || SKIP.has(root.nodeName) || root.closest?.('[translate="no"]')) return;
  for (const attr of ['placeholder', 'title', 'aria-label']) {
    if (root.hasAttribute?.(attr)) { const v = trText(root.getAttribute(attr)); if (v !== root.getAttribute(attr)) root.setAttribute(attr, v); }
  }
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT, {
    acceptNode: n => (n.nodeType === Node.ELEMENT_NODE && SKIP.has(n.nodeName)) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT,
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const n of nodes) {
    if (n.nodeType === Node.TEXT_NODE) trNode(n);
    else for (const attr of ['placeholder', 'title', 'aria-label']) {
      if (n.hasAttribute(attr)) { const v = trText(n.getAttribute(attr)); if (v !== n.getAttribute(attr)) n.setAttribute(attr, v); }
    }
  }
}

if (LANG === 'kk') {
  document.documentElement.lang = 'kk';
  const nativeAlert = window.alert.bind(window), nativeConfirm = window.confirm.bind(window);
  window.alert = m => nativeAlert(trText(String(m)));
  window.confirm = m => nativeConfirm(trText(String(m)));
  const observer = new MutationObserver(muts => {
    for (const m of muts) {
      if (m.type === 'characterData') trNode(m.target);
      else m.addedNodes.forEach(trNode);
    }
  });
  const start = () => { trNode(document.body); observer.observe(document.body, { childList: true, subtree: true, characterData: true }); };
  if (document.body) start(); else document.addEventListener('DOMContentLoaded', start);
}

